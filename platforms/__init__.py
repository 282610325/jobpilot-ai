# 岗位详情页出现这些文案 = 岗位已关闭（有效性检测用）
DEAD_WORDS = ("职位已关闭", "该职位已关闭", "职位已下线", "该职位已下线",
              "职位已失效", "该职位已失效", "职位不存在", "该职位不存在",
              "已停止招聘", "该职位已结束", "岗位已关闭", "岗位已下线",
              "该职位已暂停招聘", "已暂停招聘", "暂停招聘")


def dead_text(body):
    """页面文本命中的失效提示词；没有则返回空串。"""
    b = str(body or "")
    return next((w for w in DEAD_WORDS if w in b), "")
